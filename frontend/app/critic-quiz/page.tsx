"use client";

import { useEffect, useRef, useState } from "react";
import Link from "next/link";
import {
  ArrowLeft,
  ArrowRight,
  CheckCircle2,
  HelpCircle,
  ListChecks,
  Loader2,
  RotateCcw,
  ShieldAlert,
  Sparkles,
  XCircle,
} from "lucide-react";
import { PageHeader, ErrorNote } from "@/components/ui";
import { SignInPrompt } from "@/components/site/auth";
import { useCandidate } from "@/lib/candidate";
import {
  journeyApi,
  type CriticQuizBatch,
  type QuizGradeResponse,
} from "@/lib/journeyApi";
import { useProctor } from "@/lib/proctor/useProctor";
import { ProctorChoice, ProctorLayer, ProctorSummary } from "@/components/proctor/Proctor";

export default function CriticQuizPage() {
  const { candidate, loading: authLoading } = useCandidate();

  const [skills, setSkills] = useState<string[]>([]);
  const [selectedSkill, setSelectedSkill] = useState("");
  const [difficulty, setDifficulty] = useState("medium");
  const [count, setCount] = useState(5);

  const [loadingSkills, setLoadingSkills] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [grading, setGrading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const [batch, setBatch] = useState<CriticQuizBatch | null>(null);
  const [answers, setAnswers] = useState<(number | null)[]>([]);
  const [grade, setGrade] = useState<QuizGradeResponse | null>(null);

  const submitLatest = useRef<() => void>(() => {});

  const proctor = useProctor({
    kind: "quiz",
    signedIn: Boolean(candidate),
    onBreach: () => void submitLatest.current(),
  });

  useEffect(() => {
    if (!candidate) return;
    loadSkills();
  }, [candidate]);

  const loadSkills = async () => {
    setLoadingSkills(true);
    try {
      const res = await journeyApi.getCriticQuizSkills();
      setSkills(res.skills);
      if (res.skills.length) setSelectedSkill(res.skills[0]);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setLoadingSkills(false);
    }
  };

  const runGenerate = async () => {
    setGenerating(true);
    setError(null);
    setGrade(null);
    try {
      const res = await journeyApi.generateCriticQuiz(selectedSkill, difficulty, count);
      setBatch(res);
      setAnswers(new Array(res.questions.length).fill(null));
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setGenerating(false);
    }
  };

  const handleGenerate = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!selectedSkill) {
      setError("Please pick a skill.");
      return;
    }
    if (proctor.wanted) {
      proctor.open(selectedSkill, runGenerate);
    } else {
      await runGenerate();
    }
  };

  const handleSelectAnswer = (qIndex: number, optionIndex: number) => {
    const updated = [...answers];
    updated[qIndex] = optionIndex;
    setAnswers(updated);
  };

  const handleGrade = async () => {
    // A proctoring breach can fire this while a manual submit is running or after it finished.
    if (!batch || grading || grade) return;
    setGrading(true);
    setError(null);
    try {
      const attemptId = proctor.currentAttemptId() || undefined;
      if (proctor.phase === "running") {
        await proctor.end();
      }
      const res = await journeyApi.gradeCriticQuiz(batch.batch_id, answers, attemptId);
      setGrade(res);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setGrading(false);
    }
  };

  submitLatest.current = handleGrade;

  if (authLoading) {
    return (
      <div className="flex justify-center py-24">
        <Loader2 className="animate-spin text-muted" size={32} />
      </div>
    );
  }

  if (!candidate) {
    return (
      <div>
        <PageHeader
          eyebrow="Placement Journey · Step 4"
          title="Critic-Checked Quiz"
          lead="AI generator-critic loop: MCQs verified for factual accuracy and balance before you answer."
        />
        <div className="panel p-8 text-center max-w-lg mx-auto">
          <ListChecks size={36} className="mx-auto text-muted mb-3" />
          <p className="font-semibold text-ink">Sign in to take critic-checked quizzes</p>
          <p className="text-xs text-muted mt-1">
            Sign in to record your scores, receive targeted feedback, and advance your placement readiness.
          </p>
          <SignInPrompt />
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-8">
      <ProctorLayer proctor={proctor} />
      <PageHeader
        eyebrow="Placement Journey · Step 4"
        title="Critic-Checked Quiz"
        lead="Every MCQ is generated by an author agent and vetted by an expert critic agent to ensure strict technical rigor."
      />

      <ErrorNote message={error} />

      {/* Setup Form */}
      {!batch && (
        <form onSubmit={handleGenerate} className="panel p-6 space-y-5">
          <div className="grid gap-4 sm:grid-cols-3">
            <div>
              <label className="block text-xs font-medium text-muted">Skill to Test</label>
              <select
                value={selectedSkill}
                onChange={(e) => setSelectedSkill(e.target.value)}
                className="input mt-1 w-full text-xs"
              >
                {skills.map((s) => (
                  <option key={s} value={s}>
                    {s}
                  </option>
                ))}
              </select>
            </div>

            <div>
              <label className="block text-xs font-medium text-muted">Difficulty Level</label>
              <select
                value={difficulty}
                onChange={(e) => setDifficulty(e.target.value)}
                className="input mt-1 w-full text-xs capitalize"
              >
                {["easy", "medium", "hard"].map((d) => (
                  <option key={d} value={d}>
                    {d}
                  </option>
                ))}
              </select>
            </div>

            <div>
              <label className="block text-xs font-medium text-muted">Number of Questions</label>
              <select
                value={count}
                onChange={(e) => setCount(Number(e.target.value))}
                className="input mt-1 w-full text-xs"
              >
                {[3, 5, 10].map((c) => (
                  <option key={c} value={c}>
                    {c} Questions
                  </option>
                ))}
              </select>
            </div>
          </div>

          <div className="border-t border-hair pt-4">
            <ProctorChoice proctor={proctor} what="quiz" />
          </div>

          <button
            type="submit"
            disabled={generating}
            className="btn-ink w-full flex items-center justify-center gap-2"
          >
            {generating ? (
              <>
                <Loader2 size={16} className="animate-spin" />
                <span>Generating &amp; Critic-Checking Questions...</span>
              </>
            ) : (
              <>
                <Sparkles size={16} />
                <span>Generate Verified Quiz</span>
              </>
            )}
          </button>
        </form>
      )}

      {/* Quiz Active or Graded */}
      {batch && (
        <div className="space-y-6">
          {/* Batch Metadata banner */}
          <div className="panel p-4 flex flex-wrap items-center justify-between gap-3 text-xs">
            <div>
              <span className="font-semibold text-ink">{batch.topic_or_skill}</span>
              <span className="text-muted ml-2">({batch.difficulty} · {batch.questions.length} questions)</span>
              <span className="chip ml-3 border-ok/40 text-ok text-[11px]">
                {batch.source === "critic_generated"
                  ? `Critic Approved (${batch.attempts} attempt${batch.attempts > 1 ? "s" : ""})`
                  : "Verified Question Bank"}
              </span>
            </div>

            <button
              type="button"
              onClick={() => {
                setBatch(null);
                setGrade(null);
              }}
              className="btn-ghost py-1 text-xs"
            >
              Start Another Quiz
            </button>
          </div>

          {/* Grade Summary if Graded */}
          {grade && (
            <div className="panel p-6 border-2 border-hair space-y-4">
              <div className="flex flex-wrap items-center justify-between gap-4 border-b border-hair pb-4">
                <div>
                  <span className="eyebrow">Quiz Results</span>
                  <h3 className="font-display text-3xl font-semibold mt-1">
                    {grade.score} of {grade.total} Correct ({grade.percent}%)
                  </h3>
                </div>
                <div className="flex gap-2">
                  <button
                    type="button"
                    onClick={() => {
                      setBatch(null);
                      setGrade(null);
                    }}
                    className="btn-ink text-xs flex items-center gap-1.5"
                  >
                    <RotateCcw size={13} /> Try Another Quiz
                  </button>
                  <Link href="/voice-interview" className="btn-ghost text-xs flex items-center gap-1.5">
                    Next: Voice Assessment <ArrowRight size={13} />
                  </Link>
                </div>
              </div>
            </div>
          )}

          {/* Questions List */}
          <div className="space-y-4">
            {batch.questions.map((q, qIdx) => {
              const selectedOpt = answers[qIdx];
              const isGraded = grade !== null;
              const isCorrect = isGraded && grade.correct[qIdx];
              const review = isGraded ? grade.review[qIdx] : undefined;

              return (
                <div key={qIdx} className="panel p-5 space-y-4">
                  <div className="flex items-start justify-between gap-3">
                    <p className="font-semibold text-sm text-ink">
                      <span className="text-muted font-mono mr-2">Q{qIdx + 1}.</span>
                      {q.text}
                    </p>
                    {isGraded && (
                      <span className={`chip shrink-0 ${isCorrect ? "border-ok/40 text-ok" : "border-bad/40 text-bad"}`}>
                        {isCorrect ? "Correct" : "Incorrect"}
                      </span>
                    )}
                  </div>

                  {/* Options */}
                  <div className="grid gap-2">
                    {q.options.map((opt, oIdx) => {
                      const isChosen = selectedOpt === oIdx;
                      const isRightOption = review?.correct_index === oIdx;

                      let optClasses = "border-hair hover:bg-surface/50";
                      if (isChosen && !isGraded) {
                        optClasses = "border-ink bg-ink/[0.04] font-medium";
                      } else if (isGraded) {
                        if (isRightOption) {
                          optClasses = "border-ok bg-ok/[0.06] text-ok font-semibold";
                        } else if (isChosen && !isCorrect) {
                          optClasses = "border-bad bg-bad/[0.06] text-bad";
                        }
                      }

                      return (
                        <button
                          key={oIdx}
                          type="button"
                          disabled={isGraded}
                          onClick={() => handleSelectAnswer(qIdx, oIdx)}
                          className={`flex items-start gap-3 rounded-xl border p-3 text-left text-xs transition-colors ${optClasses}`}
                        >
                          <span className="font-mono font-semibold text-muted">
                            {"ABCD"[oIdx]}.
                          </span>
                          <span className="flex-1">{opt}</span>
                        </button>
                      );
                    })}
                  </div>

                  {/* Explanation when graded */}
                  {review?.explanation && (
                    <div className="rounded-xl border border-hair bg-surface/50 p-3 text-xs text-muted">
                      <p className="font-semibold text-ink">Explanation:</p>
                      <p className="mt-1">{review.explanation}</p>
                    </div>
                  )}
                </div>
              );
            })}
          </div>

          {/* Submit Grade Button */}
          {!grade && (
            <div className="pt-2">
              <button
                type="button"
                disabled={grading}
                onClick={handleGrade}
                className="btn-ink w-full py-3 flex items-center justify-center gap-2 text-sm"
              >
                {grading ? (
                  <>
                    <Loader2 size={16} className="animate-spin" />
                    <span>Grading and Recording Results...</span>
                  </>
                ) : (
                  <span>Submit Quiz &amp; Grade Answers</span>
                )}
              </button>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
